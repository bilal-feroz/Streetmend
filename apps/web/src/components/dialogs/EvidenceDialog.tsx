import { LoaderCircle } from 'lucide-react'
import { useEffect, useState, type ReactNode } from 'react'

// The reproducible evaluation (scripts/benchmarks/run_evaluation.py), served as written.
interface Row {
  id: string
  title: string
  claim: string
  regressions: string[]
  proposed: Record<string, string>
  exact: { status: string; ids: string[]; evaluated: number; runtime_ms: number }
  greedy: { ids: string[]; passes: boolean; minimal: boolean }
  proximity: { ids: string[]; passes: boolean; minimal: boolean }
  correct?: boolean
}
interface Evaluation {
  generated: string
  machine: string
  verification: { fixtures: Row[]; real: Row }
  network_vs_straight: { category: string; profile: string; threshold_m: number; median_ratio: number | null; overstated: number; straight_within: number; network_within: number }[]
  fix_or_build: { category: string; homes: number; budget: number; fix_gain: number; build_gain: number; winner: string; fix: string[]; fix_alone: number[] }[]
}

function H({ children }: { children: ReactNode }) {
  return <h3 className="mt-5 mb-1.5 text-[13px] font-semibold text-ink first:mt-0">{children}</h3>
}

const set = (ids: string[]) => (ids.length ? `{${ids.join(', ')}}` : '{}')

export function EvidenceBody() {
  const [ev, setEv] = useState<Evaluation | null>(null)
  const [err, setErr] = useState<string | null>(null)
  useEffect(() => {
    fetch('/api/evaluation')
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error(r.status === 404 ? 'Evaluation not generated yet: run scripts/benchmarks/run_evaluation.py' : String(r.status)))))
      .then(setEv)
      .catch((e) => setErr(String(e.message ?? e)))
  }, [])
  if (err) return <p className="text-bad-ink">{err}</p>
  if (!ev) return <p className="flex items-center gap-2"><LoaderCircle size={14} className="animate-spin" /> Loading the evaluation…</p>
  const fx = ev.verification.fixtures
  const ok = fx.filter((r) => r.correct).length
  const rows = [...fx, ev.verification.real]
  return (
    <div data-testid="evidence">
      <p>
        Generated by <code className="rounded bg-wash px-1">scripts/benchmarks/run_evaluation.py</code> on {ev.generated}. Every number is computed by that script; rerun it to reproduce.
      </p>
      <div className="mt-3 flex items-baseline gap-3 rounded-xl bg-ok-bg px-4 py-3 text-ok-ink">
        <span className="text-[26px] leading-none font-extrabold tnum" data-testid="evidence-score">{ok}/{fx.length}</span>
        <span className="text-[12.5px] font-semibold">fixtures fully correct: regression detected, valid counterexample, minimal fix verified, undoing any member regresses again.</span>
      </div>
      <H>Exact search against honest baselines</H>
      <div className="overflow-x-auto">
        <table className="w-full text-[11.5px]">
          <thead>
            <tr className="border-b border-line text-left text-[10.5px] font-extrabold tracking-[0.06em] text-ink-3 uppercase">
              <th className="py-1.5 pr-2">Case</th>
              <th className="py-1.5 pr-2">Exact fix</th>
              <th className="py-1.5 pr-2">Sets</th>
              <th className="py-1.5 pr-2">Greedy</th>
              <th className="py-1.5">Nearest first</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-line tnum">
            {rows.map((r) => (
              <tr key={r.id}>
                <td className="py-1.5 pr-2 text-ink">{r.title}</td>
                <td className="py-1.5 pr-2 font-semibold text-ink">{r.exact.ids.length ? set(r.exact.ids) : r.exact.status.replace(/_/g, ' ')}</td>
                <td className="py-1.5 pr-2">{r.exact.evaluated}</td>
                <td className={`py-1.5 pr-2 ${r.greedy.passes ? 'text-ok-ink' : 'text-bad-ink'}`}>{r.greedy.passes ? 'passes' : 'fails'} {set(r.greedy.ids)}</td>
                <td className={`py-1.5 ${r.proximity.passes ? 'text-ok-ink' : 'text-bad-ink'}`}>{r.proximity.passes ? 'passes' : 'fails'} {set(r.proximity.ids)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p className="mt-2 text-[12px]">Greedy fails when the fix needs a dependent pair, because no single ramp improves anything. Nearest-first matches the exact answer in several cases, including Charlotte, and the table shows where.</p>
      <H>Straight-line distance overstates access</H>
      <ul className="space-y-0.5 text-[12px]">
        {ev.network_vs_straight.filter((r) => r.profile === 'step_free' && r.median_ratio).map((r) => (
          <li key={r.category}>
            <b className="text-ink capitalize">{r.category}</b>: the step-free network route is a median {r.median_ratio}× the straight line; straight-line distance would place {r.overstated} more homes within {Math.round(r.threshold_m)} m.
          </li>
        ))}
      </ul>
      <H>Fix or build? The answer depends on the problem</H>
      <ul className="space-y-0.5 text-[12px]">
        {ev.fix_or_build.map((r, i) => (
          <li key={i}>
            <b className="text-ink capitalize">{r.category}</b>, {r.homes} homes, budget {r.budget}: fix +{r.fix_gain} vs build +{r.build_gain}, <b className="text-ink">{r.winner}</b>
            {r.fix_alone.some((x) => x === 0) && r.fix.length > 1 ? ' (one repair is worth nothing alone)' : ''}.
          </li>
        ))}
      </ul>
      <p className="mt-3 text-[11.5px] text-ink-3">Small deterministic fixtures test that each claim holds; they are not a scale test. No user study or field validation. Full report: docs/EVALUATION.md.</p>
    </div>
  )
}
