// Devpost gallery: real screenshots of the running app at 3:2 (1500x1000 CSS px, 1.6x = 2400x1600).
// Usage: node scripts/gallery.mjs <outDir> [baseUrl]   (API and web dev servers running, or the live site)
import { chromium } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { join } from 'node:path'

const out = process.argv[2] ?? 'gallery'
const base = process.argv[3] ?? 'http://localhost:5173'
mkdirSync(out, { recursive: true })
const browser = await chromium.launch({ args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] })
const ctx = await browser.newContext({ viewport: { width: 1500, height: 1000 }, deviceScaleFactor: 1.6 })
const page = await ctx.newPage()
const pause = (ms) => page.waitForTimeout(ms)
const shot = async (name) => { await pause(300); await page.screenshot({ path: join(out, name + '.png') }); console.log(name) }
const city = () => page.waitForFunction('(window.__sm?.layer.index?.ids.length ?? 0) > 5000', null, { timeout: 90000 })
const banner = (t) => page.getByTestId('banner-title').filter({ hasText: t }).waitFor({ timeout: 30000 })

// ---- change check ----
await page.goto(base + '/?intro=0')
await city()
await page.getByTestId('check-chip').waitFor()
await pause(4000)
await shot('03-city-today')
await page.getByTestId('propose-P1').click()
await pause(4200)
await shot('04-proposed-closure')
await page.getByTestId('run-checks').click()
await banner('ACCESS REGRESSION DETECTED')
await pause(3500)
await shot('05-regression-counterexample')
await page.getByTestId('profile-step_free').click()
await pause(4200)
await shot('06-step-free-detour')
await page.getByTestId('profile-step_free').click()
await page.getByTestId('find-fix').click()
await page.getByTestId('fix-title').waitFor()
await pause(4200)
await shot('07-minimal-fix')
await page.getByTestId('apply-fix').click()
await banner('ACCESS RESTORED')
await pause(4500)
await shot('08-verified')

// ---- access gaps ----
await page.getByTestId('data-mode').getByRole('radio', { name: 'Access gaps' }).click()
await page.getByTestId('access-title').waitFor()
await pause(5000)
await shot('09-access-gaps')
await page.getByTestId('cell-8944d84d32fffff').click()
await page.getByTestId('diagnose').waitFor()
await pause(4500)
await shot('10-diagnose')
await page.getByTestId('run-compare').click()
await page.getByTestId('intervene').waitFor()
await pause(1500)
await page.getByTestId('show-fix').click()
await pause(4200)
await shot('11-fix-wins')
await page.getByTestId('access-budget').getByRole('radio', { name: '1 repair' }).click()
await page.waitForFunction(() => document.querySelector('[data-testid=option-build]')?.textContent?.includes('Wins'), null, { timeout: 30000 })
await page.getByTestId('show-build').click()
await pause(4200)
await shot('12-build-wins')
await page.getByTestId('cat-grocery').click()
await pause(3500)
await page.locator('[data-testid^=cell-]').first().click()
await page.getByTestId('diagnose').waitFor()
await page.getByTestId('run-compare').click()
await page.getByTestId('intervene').waitFor()
await pause(4000)
await shot('13-grocery')
await page.getByTestId('ask-toggle').click()
await page.getByTestId('ask-input').fill('Which neighborhood has the poorest access to groceries?')
await page.keyboard.press('Enter')
await page.getByTestId('assistant-response').waitFor({ timeout: 30000 })
await pause(3500)
await page.getByTestId('assistant-response').scrollIntoViewIfNeeded()
await pause(800)
await shot('14-plain-english')
await page.getByTestId('more-menu').click()
await page.getByTestId('open-evidence').click()
await page.getByTestId('evidence-score').waitFor()
await pause(1500)
await shot('15-evidence')

await browser.close()
